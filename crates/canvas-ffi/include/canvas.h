// canvas.h — the C ABI of every Rust-drawn surface for Swift hosts (Packages/Canvas), linked
// through libpultik_ffi.a: the timeline (canvas_timeline_*), the estate map (canvas_map_*) and
// the diff (canvas_diff_*), all drawing on one shared device (canvas_surface_*).
//
// The host hands plain data, gestures and key intents; each engine owns its layout, hit
// testing, camera and drawing into the host's CAMetalLayer. Times are ms since the Unix epoch as
// double, NaN for none. Text crosses as UTF-8 (CanvasStr: pointer + byte length). Functions
// returning a CanvasStatus answer a panic as CANVAS_PANICKED, never an unwind; a failure's
// message, when `error` is passed, is an owned string to free with canvas_string_free.
//
// Every handle is used by the main thread alone and draws only between its _attach and _detach
// (or _free). The device they share is built on the first attach and dropped by
// canvas_surface_release once no surface is attached.

