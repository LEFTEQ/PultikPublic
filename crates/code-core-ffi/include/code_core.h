// valid for the call; `out` is valid for a write. Free the result with
// `code_core_symbol_list_free`.
CodeCoreStatus code_core_symbols_definitions(struct CodeCoreSymbols *symbols,
                                             struct CodeCoreStr repo,
                                             struct CodeCoreStr head,
                                             struct CodeCoreStr name,
                                             struct CodeCoreStr path,
                                             const struct CodeCoreStr *imports,
                                             size_t import_count,
                                             struct CodeCoreSymbolList **out,
                                             char **error);

// Every use of `name` in repo@head, by path and line; a spot that also defines it is left
// out.
//
// # Safety
// As `code_core_symbols_definitions`.
CodeCoreStatus code_core_symbols_references(struct CodeCoreSymbols *symbols,
                                            struct CodeCoreStr repo,
                                            struct CodeCoreStr head,
                                            struct CodeCoreStr name,
                                            struct CodeCoreSymbolList **out,
                                            char **error);

// Free a symbol list; null is a no-op.
//
// # Safety
// `list` is null or a symbol list of this library, freed once.
void code_core_symbol_list_free(struct CodeCoreSymbolList *list);

// The repo paths a file imports, for ranking definitions (TS and JS relative modules, Go
// import paths' last two components, Rust `mod` files and `crate::` paths, PHP `use`
// classes); best effort.
//
// # Safety
// Texts are valid for the call; `out` is valid for a write. Free the result with
// `code_core_strings_free`.
CodeCoreStatus code_core_imports(struct CodeCoreStr text,
                                 uint32_t language,
                                 struct CodeCoreStr path,
                                 struct CodeCoreStrings **out,
                                 char **error);

// Whether `path` is a file `imports` names, or lies in a directory it names (as path
// suffixes).
//
// # Safety
// Texts and `imports` (`import_count` texts) are valid for the call; `imported` is valid
// for a write.
CodeCoreStatus code_core_imported(struct CodeCoreStr path,
                                  const struct CodeCoreStr *imports,
                                  size_t import_count,
                                  bool *imported,
                                  char **error);

// The language a path's extension (or name) highlights as, or `CODE_CORE_NONE` for plain
// text.
//
// # Safety
// `path` is valid for the call; `language` is valid for a write.
CodeCoreStatus code_core_language(struct CodeCoreStr path, uint32_t *language, char **error);

// Whether a language's tags query names definitions and references (the data and prose
// grammars ship none).
//
// # Safety
// `has_tags` is valid for a write.
CodeCoreStatus code_core_language_has_tags(uint32_t language, bool *has_tags, char **error);

// Highlight `text` in one parse (Pultík's `SyntaxEngine.highlight`): every line's runs.
//
// # Safety
// `text` is valid for the call; `out` is valid for a write. Free the result with
// `code_core_tokens_free`.
CodeCoreStatus code_core_highlight(struct CodeCoreStr text,
                                   uint32_t language,
                                   struct CodeCoreTokens **out,
                                   char **error);

// Free a highlight; null is a no-op.
//
// # Safety
// `tokens` is null or came from `code_core_highlight`, freed once.
void code_core_tokens_free(struct CodeCoreTokens *tokens);

// The definitions and references `text`'s tags query names (Pultík's
// `SyntaxEngine.tags`); none for a language without one.
//
// # Safety
// `text` is valid for the call; `out` is valid for a write. Free the result with
// `code_core_tags_free`.
CodeCoreStatus code_core_tags(struct CodeCoreStr text,
                              uint32_t language,
                              struct CodeCoreTags **out,
                              char **error);

// Free tags; null is a no-op.
//
// # Safety
// `tags` is null or came from `code_core_tags`, freed once.
void code_core_tags_free(struct CodeCoreTags *tags);

// Each top-level pattern's depth of node structure in a query source, in pattern order: the
// paint rule's tie-break (`syntax::specificity`).
//
// # Safety
// `source` is valid for the call; `out` is valid for a write. Free the result with
// `code_core_numbers_free`.
CodeCoreStatus code_core_specificity(struct CodeCoreStr source,
                                     struct CodeCoreNumbers **out,
                                     char **error);

