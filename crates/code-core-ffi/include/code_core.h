// bytes and converts once, here. Every result a function allocates has its own *_free; a
// CodeCoreStr inside a result borrows from that result and dies with it.
//
// Thread safety: the free functions may run on any thread. A handle (CodeCoreSymbols,
// CodeCoreSymbolBuilder, CodeCoreGrep) is used by one thread at a time; a CodeCoreMatcher is
// immutable and may be shared.

