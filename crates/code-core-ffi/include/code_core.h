// Every function returns a CodeCoreStatus (0 is CODE_CORE_OK) and answers through out
// parameters; a panic inside the core is caught and returned as CODE_CORE_PANICKED, never
// unwound into the caller. A failure's message, when the caller passes `error`, is an owned
// NUL-terminated string: free it with code_core_string_free.
//
// Text crosses as UTF-8 (CodeCoreStr: pointer + byte length, never NUL-terminated). Positions
