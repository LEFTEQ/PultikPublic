// timeline.h — the C ABI of the timeline engine for Swift hosts (Packages/Timeline), linked
// through libpultik_ffi.a.
//
// The host hands plain data (jobs, bins, groups of rows), gestures and key intents; the engine
// owns marks, layout, hit testing, stepping, the camera and drawing into the host's
// CAMetalLayer. Times are ms since the Unix epoch as double, NaN for none. Text crosses as UTF-8
// (TimelineStr: pointer + byte length). Functions returning a TimelineStatus answer a panic as
// TIMELINE_PANICKED, never an unwind; a failure's message, when `error` is passed, is an owned
// string to free with timeline_string_free.
//
// A handle is used by one thread at a time. Its GPU device exists only between
// timeline_attach and timeline_detach (or timeline_free).

